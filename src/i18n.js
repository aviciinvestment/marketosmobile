const STORAGE_KEY = 'marketos_landing_lang';

let currentLang = 'en';

const listeners = new Set();

export function getStoredLang() {
  return currentLang;
}

export async function hydrateLang() {
  try {
    const saved = await AsyncStorage.getItem(STORAGE_KEY);
    if (saved && LANGUAGE_CODES.includes(saved)) {
      currentLang = saved;
      listeners.forEach((l) => l(currentLang));
    }
  } catch {
    // storage unavailable - keep default
  }
  return currentLang;
}

export function setAppLang(lang) {
  currentLang = lang;
  try {
    AsyncStorage.setItem(STORAGE_KEY, lang);
  } catch {
    // ignore
  }
  listeners.forEach((l) => l(lang));
}

export function useAppLang() {
  const [lang, setLang] = useState(currentLang);
  useEffect(() => {
    const listener = (next) => setLang(next);
    listeners.add(listener);
    return () => {
      listeners.delete(listener);
    };
  }, []);
  return lang;
}

export function t(lang, key) {
  const dict = UI_STRINGS[lang];
  return (dict && dict[key]) || UI_STRINGS.en[key] || key;
}

export function useAppT() {
  const lang = useAppLang();
  return (key) => t(lang, key);
}

export function useAppTF() {
  const lang = useAppLang();
  return (key, ...args) => tf(lang, key, ...args);
}

export function tf(lang, key, ...args) {
  const template = t(lang, key);
  return template.replace(/\{(\d+)\}/g, (match, i) => {
    const v = args[Number(i)];
    return v !== undefined ? String(v) : match;
  });
}

